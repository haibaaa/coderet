"""Generate report/numbers.tex from experiments/results/*.json.

Every number in the paper that comes from an experiment is produced here, so
the PDF can be rebuilt from the raw results. Usage:
    uv run python report/make_numbers.py
"""

from __future__ import annotations

import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "experiments" / "results"
OUT = Path(__file__).resolve().parent / "numbers.tex"
QUERIES = ROOT / "examples" / "flask_queries.jsonl"


def load(name: str) -> dict | None:
    p = RES / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def summary(report: dict, mode: str) -> dict[str, float]:
    """Unrounded per-mode means (the eval report's own summary is rounded to
    4 decimals, and rounding that again to 3 can give the wrong last digit)."""
    pq = report["modes"][mode]["per_query"]
    keys = [k for k in pq[0] if k not in {"id", "query", "top", "first_relevant_rank"}]
    return {k: sum(q[k] for q in pq) / len(pq) for k in keys}


def f3(x: float) -> str:
    return f"{x:.3f}"


def per_query_rr(report: dict, mode: str) -> dict[str, float]:
    out = {}
    for q in report["modes"][mode]["per_query"]:
        r = q["first_relevant_rank"]
        out[q["id"]] = 1.0 / r if r and r <= 10 else 0.0
    return out


def paired_randomisation(a: dict, b: dict, n: int = 10_000, seed: int = 0) -> tuple[float, float, int, int]:
    """Two-sided paired sign-flip test on mean difference of b - a."""
    ids = sorted(a)
    diffs = [b[i] - a[i] for i in ids]
    obs = sum(diffs) / len(diffs)
    rng = random.Random(seed)
    extreme = 0
    for _ in range(n):
        s = sum(d if rng.random() < 0.5 else -d for d in diffs) / len(diffs)
        if abs(s) >= abs(obs) - 1e-12:
            extreme += 1
    wins = sum(1 for d in diffs if d > 0)
    losses = sum(1 for d in diffs if d < 0)
    return obs, (extreme + 1) / (n + 1), wins, losses


def main() -> None:
    lines: list[str] = ["% generated by report/make_numbers.py -- do not edit"]
    d = lambda k, v: lines.append(f"\\newcommand{{\\{k}}}{{{v}}}")

    main_r = load("main")
    s = {m: summary(main_r, m) for m in main_r["modes"]}
    d("NQueries", main_r["num_queries"])
    d("DenseAccOne", f3(s["dense"]["hit@1"]))
    d("DenseMRR", f3(s["dense"]["mrr@10"]))
    d("DenseRFive", f3(s["dense"]["recall@5"]))
    d("LexAccOne", f3(s["lexical"]["hit@1"]))
    d("LexMRR", f3(s["lexical"]["mrr@10"]))
    d("LexRFive", f3(s["lexical"]["recall@5"]))

    qs = [json.loads(l) for l in QUERIES.read_text().splitlines() if l.strip() and not l.startswith("#")]
    words = [len(q["query"].split()) for q in qs]
    d("QWords", f"{sum(words) / len(words):.1f}")
    d("QWordsMin", min(words))
    d("QWordsMax", max(words))
    d("NTargets", sum(len(q["relevant"]) for q in qs))

    # import-resolution audit (measured on the index, see paper Section V-E)
    false_edges, naive_total = 28, 343
    d("FalseEdges", false_edges)
    d("FalseEdgePct", f"{100 * false_edges / naive_total:.1f}")

    # hybrid at lambda_lex = 0.05
    h5 = summary(load("fusion-0.05"), "hybrid")
    lines.append("\\newcommand{\\HybFiveP}[1]{\\csname hybp#1\\endcsname}")
    lines.append("\\newcommand{\\HybFiveR}[1]{\\csname hybr#1\\endcsname}")
    lines.append("\\newcommand{\\HybFiveF}[1]{\\csname hybf#1\\endcsname}")
    for k in (3, 5, 10):
        lines.append(f"\\expandafter\\def\\csname hybp{k}\\endcsname{{{f3(h5[f'precision@{k}'])}}}")
        lines.append(f"\\expandafter\\def\\csname hybr{k}\\endcsname{{{f3(h5[f'recall@{k}'])}}}")
        lines.append(f"\\expandafter\\def\\csname hybf{k}\\endcsname{{{f3(h5[f'f1@{k}'])}}}")

    # main results table, bold = best per column (ties all bold)
    cols = ["hit@1", "precision@3", "recall@3", "f1@3", "precision@5", "recall@5", "f1@5",
            "recall@10", "f1@10", "mrr@10", "ndcg@10"]
    table = [
        ("BM25 (lexical)", s["lexical"]),
        ("Dense (CodeRankEmbed)", s["dense"]),
        ("Hybrid RRF ($\\lambda_{\\text{lex}}=1$)", s["hybrid"]),
        ("Hybrid RRF ($\\lambda_{\\text{lex}}=0.05$)", h5),
    ]
    best = {c: max(round(r[c], 3) for _, r in table) for c in cols}
    body = []
    for name, r in table:
        cells = [f"\\textbf{{{f3(r[c])}}}" if round(r[c], 3) == best[c] else f3(r[c]) for c in cols]
        body.append(name + " & " + " & ".join(cells) + " \\\\")
    d("MainRows", "\n".join(body))

    # significance tests
    dense = per_query_rr(main_r, "dense")
    rows = []
    comparisons = [
        ("Dense vs.\\ BM25", per_query_rr(main_r, "lexical"), dense),
        ("Dense vs.\\ hybrid ($\\lambda{=}1$)", per_query_rr(main_r, "hybrid"), dense),
        ("Hybrid ($\\lambda{=}0.05$) vs.\\ dense", dense, per_query_rr(load("fusion-0.05"), "hybrid")),
    ]
    for label, a, b in comparisons:
        delta, p, w, l = paired_randomisation(a, b)
        p_txt = "$<$0.001" if p < 0.001 else f"{p:.3f}"
        rows.append(f"{label} & {delta:+.3f} & {p_txt} & {w} / {l} \\\\")
        if "lambda{=}1$" in label:
            d("SigHybP", f"{p:.3f}")

    # ablations (dense retrieval)
    nohead, window = load("noheader"), load("window")
    sd = s["dense"]
    n, w, wl = summary(nohead, "dense"), summary(window, "dense"), summary(window, "lexical")
    row = lambda name, chunks, r: (f"{name} & {chunks} & {f3(r['hit@1'])} & {f3(r['recall@5'])} & "
                                   f"{f3(r['mrr@10'])} & {f3(r['ndcg@10'])} \\\\")
    abl_rows = [
        row("Full system", main_r["index_stats"]["chunks"], sd),
        row("$-$ contextual header", nohead["index_stats"]["chunks"], n),
        row("Fixed 60-line windows", window["index_stats"]["chunks"], w),
        "\\midrule",
        row("BM25, syntax chunks", main_r["index_stats"]["chunks"], s["lexical"]),
        row("BM25, 60-line windows", window["index_stats"]["chunks"], wl),
    ]
    d("AblRows", "\n".join(abl_rows))

    rr_full = per_query_rr(main_r, "dense")
    dh, ph, wh, lh = paired_randomisation(rr_full, per_query_rr(nohead, "dense"))
    dw, pw, ww, lw = paired_randomisation(per_query_rr(window, "dense"), rr_full)
    ptxt = lambda p: "$<$0.001" if p < 0.001 else f"{p:.3f}"
    rows.append(f"Syntax chunks vs.\\ windows (dense) & {dw:+.3f} & {ptxt(pw)} & {ww} / {lw} \\\\")
    rows.append(f"No header vs.\\ header (dense) & {dh:+.3f} & {ptxt(ph)} & {wh} / {lh} \\\\")

    dr5 = 100 * (sd["recall@5"] - w["recall@5"])
    d("WinDRFive", f"{dr5:.1f}")
    d("AblText",
      f"\\textbf{{Syntax-aware chunking.}} Replacing definition-level chunks by fixed 60-line "
      f"windows (with 10 lines of overlap) reduces dense Acc@1 from {f3(sd['hit@1'])} to "
      f"{f3(w['hit@1'])}, Recall@5 from {f3(sd['recall@5'])} to {f3(w['recall@5'])} and MRR@10 from "
      f"{f3(sd['mrr@10'])} to {f3(w['mrr@10'])} ($p = {pw:.3f}$, Table~\\ref{{tab:sig}}). BM25 also "
      f"degrades (MRR@10 {f3(s['lexical']['mrr@10'])} $\\rightarrow$ {f3(wl['mrr@10'])}). The drop occurs "
      f"although the evaluation is lenient towards windows: a window counts as relevant whenever it "
      f"overlaps the target definition, even if most of it is unrelated code. Windows mix several "
      f"definitions into one vector, and their headers carry no symbol name. "
      f"\\textbf{{Contextual header.}} Removing the \\texttt{{File:}}/\\texttt{{Symbol:}} header gives a "
      f"mixed result: Acc@1 rises from {f3(sd['hit@1'])} to {f3(n['hit@1'])} and MRR@10 from "
      f"{f3(sd['mrr@10'])} to {f3(n['mrr@10'])}, but Recall@5 falls from {f3(sd['recall@5'])} to "
      f"{f3(n['recall@5'])}. The difference in reciprocal rank is not significant ($p = {ph:.3f}$; "
      f"{wh} queries improve and {lh} worsen). The changed queries show two opposing effects. With the "
      f"header, short definitions whose symbol names contain query words rank higher; for the "
      f"template-loader query, \\texttt{{Blueprint.app\\_template\\_global}} outranks the correct "
      f"\\texttt{{DispatchingJinjaLoader}} (rank 9 vs.\\ rank 1 without header). Without the header, "
      f"tests and documentation describing the same behaviour rank above the implementation; "
      f"\\texttt{{test\\_blueprint\\_prefix\\_slash}} displaces "
      f"\\texttt{{BlueprintSetupState.add\\_url\\_rule}} (rank 6 vs.\\ rank 1 with header). The header "
      f"is therefore not a reliable improvement for this model and benchmark.")
    d("CastCompare",
      f"Syntax-aware vs.\\ 60-line windows: +{dr5:.1f} Recall@5 points (dense retrieval, Flask)")
    d("CastDiscussion",
      f"Zhang \\emph{{et al.}} report that AST-based chunking improves Recall@5 by 4.3 points over "
      f"fixed-size chunking on RepoEval. Our ablation points in the same direction with a larger "
      f"effect, +{dr5:.1f} Recall@5 points and +{f3(sd['mrr@10'] - w['mrr@10'])} MRR@10. The settings "
      f"differ (RepoEval targets code completion with code queries, whereas our queries are natural "
      f"language and our windows are line-based rather than size-balanced), so the magnitudes are not "
      f"directly comparable, but both studies indicate that chunk boundaries aligned with the syntax "
      f"tree matter for code retrieval.")
    d("AblConclusion",
      f"Syntax-aware chunking is essential: fixed windows lower Recall@5 by {dr5:.1f} points, "
      f"in line with prior work on AST chunking, whereas the contextual header has no significant effect.")

    # ---------------- held-out set and test-aware graph reranking ----------------
    import hashlib
    ho_path = ROOT / "examples" / "flask_queries_heldout.jsonl"
    d("HoSha", hashlib.sha256(ho_path.read_bytes()).hexdigest()[:12])
    hob, hog = load("heldout-baseline"), load("heldout-graph")
    devg = load("graph-dev")
    sweep = load("graph-sweep-dev")
    d("HoQueries", hob["num_queries"])
    ch = sweep["chosen"]
    d("GBeta", f"{ch['graph_beta']:g}")
    d("GTop", ch["graph_top"])
    d("GTestW", f"{ch['test_weight']:g}")

    sb = {m: summary(hob, m) for m in ("dense", "lexical", "hybrid")}
    sg = {m: summary(hog, m) for m in ("dense", "lexical", "hybrid")}
    sdg = {m: summary(devg, m) for m in ("dense", "hybrid")}
    cols4 = ["hit@1", "recall@5", "mrr@10", "ndcg@10"]
    fmt = lambda r: " & ".join(f3(r[c]) for c in cols4)
    d("HoRows", "\n".join([
        f"BM25 & {fmt(s['lexical'])} & {fmt(sb['lexical'])} \\\\",
        f"Dense & {fmt(s['dense'])} & {fmt(sb['dense'])} \\\\",
        f"Hybrid ($\\lambda_{{\\text{{lex}}}}{{=}}1$) & {fmt(s['hybrid'])} & {fmt(sb['hybrid'])} \\\\",
        "\\midrule",
        f"BM25 + graph & -- & -- & -- & -- & {fmt(sg['lexical'])} \\\\",
        f"Dense + graph & {fmt(sdg['dense'])} & {fmt(sg['dense'])} \\\\",
        f"Hybrid + graph & {fmt(sdg['hybrid'])} & {fmt(sg['hybrid'])} \\\\",
    ]))
    for key, val in [("HoDenseMRR", sb["dense"]["mrr@10"]), ("HoHybMRR", sb["hybrid"]["mrr@10"]),
                     ("HoLexMRR", sb["lexical"]["mrr@10"]), ("HoGDenseMRR", sg["dense"]["mrr@10"]),
                     ("HoDenseAcc", sb["dense"]["hit@1"]), ("HoGDenseAcc", sg["dense"]["hit@1"]),
                     ("DevGDenseMRR", sdg["dense"]["mrr@10"])]:
        d(key, f3(val))

    # sweep figure coordinates: dev dense MRR@10 vs beta, per (graph_top, test_weight)
    for top in (5, 10):
        for tw in (1.0, 0.5):
            pts = " ".join(f"({r['graph_beta']},{r['dense_mrr@10']:.4f})" for r in sweep["sweep"]
                           if r["graph_top"] == top and r["test_weight"] == tw)
            d(f"Sweep{'Five' if top == 5 else 'Ten'}{'Full' if tw == 1.0 else 'Half'}", pts)
    d("SweepBase", f"{sweep['baseline']['dense']['mrr@10']:.4f}")

    # significance: graph reranking (dense), dev / held-out / pooled
    def rrs(rep, mode="dense"):
        return per_query_rr(rep, mode)
    gd = paired_randomisation(rrs(main_r), rrs(devg))
    gh = paired_randomisation(rrs(hob), rrs(hog))
    pa = {**{"d" + k: v for k, v in rrs(main_r).items()}, **{"h" + k: v for k, v in rrs(hob).items()}}
    pb = {**{"d" + k: v for k, v in rrs(devg).items()}, **{"h" + k: v for k, v in rrs(hog).items()}}
    gp = paired_randomisation(pa, pb)
    for tag, (dl, p, w, l), label in (("Dev", gd, "Graph rerank, dense (dev)"),
                                      ("Ho", gh, "Graph rerank, dense (held-out)"),
                                      ("Pool", gp, "Graph rerank, dense (pooled, $n{=}72$)")):
        rows.append(f"{label} & {dl:+.3f} & {ptxt(p)} & {w} / {l} \\\\")
        d(f"G{tag}Delta", f"{dl:+.3f}")
        d(f"G{tag}P", f"{p:.3f}")
        d(f"G{tag}WL", f"{w}/{l}")
    hd = paired_randomisation(rrs(hob, "hybrid"), rrs(hob, "dense"))
    d("HoDenseVsHybP", f"{hd[1]:.3f}")
    d("SigRows", "\n".join(rows))

    lat = load("latency")
    d("QueryLatency",
      f"Loading the encoder takes {lat['model_load_seconds']:.1f}\\,s once per process; after that a "
      f"query takes a median of {lat['dense']['median_ms']:.0f}\\,ms in dense mode, "
      f"{lat['hybrid']['median_ms']:.0f}\\,ms in hybrid mode and {lat['lexical']['median_ms']:.1f}\\,ms "
      f"for BM25 alone ({lat['queries']} queries); the additional cost of dense retrieval covers "
      f"query encoding and the exhaustive scan.")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    for r in rows:
        print(r)


if __name__ == "__main__":
    main()
